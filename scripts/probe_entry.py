"""A Remotion entry that bundles one primitive group on its own, one composition per variant
(`<Name>--<variant>`, laid out by ProbeFrame). Builders render through it so another group's
half-written files can never break their bundle. Used by probe_group.py and compare_sheets.py --group.
"""
from __future__ import annotations

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRIM = ROOT / "src" / "motion" / "primitives"


def group_primitives(group: str) -> list[str]:
    """Names in src/motion/primitives/<group>/ with both <Name>.spec.ts and <Name>.tsx exporting Demo."""
    out = []
    for spec in sorted((PRIM / group).glob("*.spec.ts")):
        name = spec.name[: -len(".spec.ts")]
        comp = spec.with_name(f"{name}.tsx")
        if comp.exists() and re.search(r"export const Demo\b", comp.read_text()):
            out.append(name)
    return out


def write_group_entry(group: str) -> Path:
    names = group_primitives(group)
    if not names:
        raise SystemExit(f"no primitive with a spec and a Demo in src/motion/primitives/{group}/")
    d = ROOT / ".tmp" / "probe" / group
    d.mkdir(parents=True, exist_ok=True)
    src = "../../../src"
    imports = []
    items = []
    for i, n in enumerate(names):
        imports.append(f"import {{spec as s{i}}} from '{src}/motion/primitives/{group}/{n}.spec';")
        imports.append(f"import {{Demo as d{i}}} from '{src}/motion/primitives/{group}/{n}';")
        items.append(f"\t{{spec: s{i}, Demo: d{i}}},")
    entry = d / "entry.tsx"
    entry.write_text(
        f"// Generated by scripts/probe_entry.py: the {group} primitives on their own, one composition per variant.\n"
        "import type React from 'react';\n"
        "import {Composition, registerRoot} from 'remotion';\n"
        f"import {{probeLength}} from '{src}/compositions/probe';\n"
        f"import {{ProbeFrame}} from '{src}/compositions/ProbeFrame';\n"
        f"import {{loadFonts}} from '{src}/motion/engine/loadFonts';\n"
        f"import type {{DemoProps, PrimitiveSpec}} from '{src}/motion/primitives/types';\n"
        + "\n".join(imports)
        + "\n\nloadFonts();\n\n"
        "const ITEMS: {spec: PrimitiveSpec; Demo: React.FC<DemoProps>}[] = [\n" + "\n".join(items) + "\n];\n\n"
        "const COMPS = ITEMS.flatMap(({spec, Demo}) =>\n"
        "\tObject.keys(spec.variants).map((variant) => {\n"
        "\t\tconst C: React.FC = () => <ProbeFrame spec={spec} Demo={Demo} variant={variant} />;\n"
        "\t\treturn {id: `${spec.name}--${variant}`, length: probeLength(spec, variant), C};\n"
        "\t}),\n);\n\n"
        "const Root: React.FC = () => (\n\t<>\n"
        "\t\t{COMPS.map(({id, length, C}) => (\n"
        "\t\t\t<Composition key={id} id={id} component={C} durationInFrames={length} fps={60} width={1920} height={1080} />\n"
        "\t\t))}\n\t</>\n);\n\n"
        "registerRoot(Root);\n"
    )
    return entry
