"""Write src/motion/tokens/timing.ts from the measurements (step 7).

  python gen_timing.py

SHOT        shot lengths of the GRAPHICS and MIXED segments (synthesis.json graphics_tempo): p10, p25,
            median, p75, p90; plus the median shot inside the measured accelerations
DURATION    per technique family (technique id category): median measured duration of its curves
TRANSITION  per boundary type: median length (hard cuts are 0)
STAGGER     frames between successive units: char / word / line from techniques.json typography
            (reveal_unit, stagger); item from moves[].stagger of techniques that move no text
Every value is a median of measured numbers rounded to whole frames; each comment gives n and the range.
"""
import re

import numpy as np

from common import ANALYSIS, ROOT, load_json, load_registry

FAMILY = {"trans": "transition", "cam": "camera", "bg": "background", "3d": "object3d", "fx": "effect"}
UNIT = {"char": "char", "letter": "char", "character": "char", "glyph": "char", "word": "word", "line": "line"}


def num(x):
    if isinstance(x, (int, float)):
        return float(x)
    m = re.search(r"-?\d+(?:\.\d+)?", str(x or ""))
    return float(m.group()) if m else None


def camel(s):
    parts = re.split(r"[^a-zA-Z0-9]+", s)
    out = parts[0].lower() + "".join(p[:1].upper() + p[1:].lower() for p in parts[1:])
    return out if re.match(r"[a-zA-Z_]", out) else f"t{out}"


def entry(name, values, doc):
    a = np.asarray(values, float)
    lo, hi = float(a.min()), float(a.max())
    rng = f"{lo:g}-{hi:g}" if lo != hi else f"{lo:g}"
    return f"\t/** {doc}: median of {len(a)} measured (range {rng}) */\n\t{name}: {int(round(float(np.median(a))))},"


def main():
    syn = load_json(ANALYSIS / "synthesis.json")
    gt = syn["graphics_tempo"]
    accel = [f for v in syn["per_video"] for r in v["accelerations"] for f in r["frames"]]
    shot = [
        f"\t/** p10 of {gt['n']} graphics shots: the shortest cuts */\n\tflash: {int(round(gt['p10']))},",
        f"\t/** p25 */\n\tquick: {int(round(gt['p25']))},",
        f"\t/** median: the base shot length (StyleDemo is checked against it) */\n\tbase: {int(round(gt['median']))},",
        f"\t/** p75 */\n\tlong: {int(round(gt['p75']))},",
        f"\t/** p90: holds */\n\thold: {int(round(gt['p90']))},",
    ]
    if accel:
        shot.append(entry("accelerated", accel, "shot inside an accelerating run of >= 3 short shots"))
    dur = []
    for cat, d in sorted(syn["curves_by_category"].items()):
        frames = [c["measured_frames"] for c in d["curves"]]
        dur.append(entry(FAMILY.get(cat, camel(cat)), frames, f"{FAMILY.get(cat, cat)} curves (technique category {cat})"))
    trans = []
    for typ, d in sorted(syn["transitions"].items()):
        frames = [x["frames"] for x in d["instances"]]
        trans.append(entry(camel(typ), frames, f"{typ} boundaries"))
    stag = {"char": [], "word": [], "line": [], "item": []}
    for v in load_registry():
        data = load_json(v.dir / "techniques.json", {"techniques": []})
        for r in data["techniques"]:
            ty = r.get("typography")
            if ty:
                u = UNIT.get(str(ty.get("reveal_unit") or "").lower())
                s = num(ty.get("stagger"))
                if u and s is not None and s > 0:
                    stag[u].append(s)
            else:
                for m in r.get("moves") or []:
                    s = num(m.get("stagger"))
                    if s is not None and s > 0:
                        stag["item"].append(s)
    stagger = [entry(k, vals, f"between successive {k}s") for k, vals in stag.items() if vals]
    body = (
        "// Timing tokens: frames at 60 fps, every value a median of the measured references.\n"
        "// Generated by scripts/analysis/gen_timing.py from analysis/synthesis.json and analysis/<video>/techniques.json.\n"
        "// Measured curves themselves are motions in measured.ts; these are for composing new work.\n\n"
        "/** Every duration token is written at 60 fps, the frame rate of the 1080p references. */\n"
        "export const REF_FPS = 60;\n\n"
        "/** Shot lengths of the references' GRAPHICS and MIXED segments (LIVE excluded). */\n"
        "export const SHOT = {\n" + "\n".join(shot) + "\n} as const;\n\n"
        "/** How long a movement takes, by technique family: median active-window duration of its measured curves. */\n"
        "export const DURATION = {\n" + "\n".join(dur) + "\n} as const;\n\n"
        "/** Boundary lengths by type: frames from the first to the last frame of the transition (a hard cut is 0). */\n"
        "export const TRANSITION = {\n" + "\n".join(trans) + "\n} as const;\n\n"
        "/** Frames between the starts of successive units of one reveal or one build. */\n"
        "export const STAGGER = {\n" + "\n".join(stagger) + "\n} as const;\n"
    )
    out = ROOT / "src" / "motion" / "tokens" / "timing.ts"
    out.write_text(body)
    print(f"timing.ts: SHOT {len(shot)}, DURATION {len(dur)}, TRANSITION {len(trans)}, STAGGER {len(stagger)} "
          f"({', '.join(f'{k} n={len(v)}' for k, v in stag.items())})")


if __name__ == "__main__":
    main()
