"""Write src/motion/tokens/easing.ts and src/motion/tokens/measured.ts from analysis/tokens.json.

Ease tokens are named by their shape, not by the reference they came from:
  out*    fast start, long settle (time to half way < 0.38 of the duration)
  in*     slow start, fast end (> 0.62)
  inOut*  symmetric-ish S curves, named by peak steepness
  *Over   overshoots the end value (y > 1 inside the curve)
Strength words: soft < firm < strong < snap (out), gentle < accelerate < launch (in),
glide < sweep < whip (inOut). Springs: springBouncy / springLively / springFirm / springCritical.

measured.ts holds one motion per measured curve (duration + ease name), keyed by curve id; the
primitive specs pick their variants' motions from it, so every number in a spec is a token.

  python gen_tokens.py
"""
from __future__ import annotations

import json
import math
from collections import Counter

import numpy as np

from common import ANALYSIS, ROOT, load_json

OUT_EASE = ROOT / "src" / "motion" / "tokens" / "easing.ts"
OUT_MEASURED = ROOT / "src" / "motion" / "tokens" / "measured.ts"


def bezier_xy(x1, y1, x2, y2, n=4001):
    t = np.linspace(0, 1, n)
    xs = 3 * (1 - t) ** 2 * t * x1 + 3 * (1 - t) * t ** 2 * x2 + t ** 3
    ys = 3 * (1 - t) ** 2 * t * y1 + 3 * (1 - t) * t ** 2 * y2 + t ** 3
    return xs, ys


def describe(e: dict) -> tuple[str, str]:
    """(shape name, one-line description) from the curve itself."""
    if e["kind"] == "spring":
        z = e["damping_ratio"]
        if z < 0.4:
            return "springBouncy", f"spring, damping ratio {z:.2f}: several visible bounces"
        if z < 0.65:
            return "springLively", f"spring, damping ratio {z:.2f}: one clear overshoot"
        if z < 0.95:
            return "springFirm", f"spring, damping ratio {z:.2f}: a small overshoot"
        return "springCritical", f"spring, damping ratio {z:.2f}: no overshoot, soft landing"
    xs, ys = bezier_xy(e["x1"], e["y1"], e["x2"], e["y2"])
    grid = np.linspace(0, 1, 401)
    y = np.interp(grid, xs, ys)
    t50 = float(grid[np.argmax(y >= 0.5)])
    slope = np.gradient(y, grid)
    peak = float(slope.max())
    over = float(y.max()) > 1.005
    under = float(y.min()) < -0.005
    if t50 < 0.38:
        word = "snap" if t50 < 0.12 else "strong" if t50 < 0.2 else "firm" if t50 < 0.29 else "soft"
        name = f"out{word.capitalize()}"
        desc = f"fast start, long settle: half way at {100 * t50:.0f}% of the duration"
    elif t50 > 0.62:
        word = "launch" if t50 > 0.85 else "accelerate" if t50 > 0.74 else "gentle"
        name = f"in{word.capitalize()}"
        desc = f"slow start, fast end: half way at {100 * t50:.0f}% of the duration"
    else:
        word = "whip" if peak > 3.2 else "sweep" if peak > 2.1 else "glide"
        name = f"inOut{word.capitalize()}"
        desc = f"S curve, half way at {100 * t50:.0f}%, peak speed {peak:.1f}x the average"
    if over:
        name += "Over"
        desc += f", overshoots to {100 * float(y.max()):.0f}%"
    if under:
        name += "Anticipate"
        desc += f", pulls back to {100 * float(y.min()):.0f}% first"
    return name, desc


def ts_num(x: float) -> str:
    return f"{x:.4f}".rstrip("0").rstrip(".") if not float(x).is_integer() else str(int(x))


def main():
    tok = load_json(ANALYSIS / "tokens.json")
    eases = tok["eases"]
    # stable, readable names; same shape class gets a numeric suffix by number of uses
    order = sorted(eases, key=lambda k: -eases[k]["uses"])
    taken: Counter = Counter()
    rename, lines = {}, []
    for k in order:
        e = eases[k]
        base, desc = describe(e)
        taken[base] += 1
        name = base if taken[base] == 1 else f"{base}{taken[base]}"
        rename[k] = name
        cats = ", ".join(f"{c} {n}" for c, n in list(e["categories"].items())[:4])
        if e["kind"] == "bezier":
            body = f"bezier({ts_num(e['x1'])}, {ts_num(e['y1'])}, {ts_num(e['x2'])}, {ts_num(e['y2'])})"
        else:
            body = f"springEase({ts_num(e['stiffness'])}, {ts_num(e['damping'])}, {ts_num(e['mass'])})"
        lines.append(f"\t/** {desc}. {e['uses']} measured curves ({cats}). */\n\t{name}: {body},")

    ease_ts = f"""// Easing tokens: the shapes that reproduce every measured curve of the references.
// Generated by scripts/analysis/gen_tokens.py from analysis/tokens.json; names describe the shape.
// A motion is an ease plus a duration in frames at 60 fps; spring tokens are stretched to that
// duration (Remotion spring durationInFrames), so only their damping ratio matters.

export type Ease =
	| {{kind: 'bezier'; x1: number; y1: number; x2: number; y2: number}}
	| {{kind: 'spring'; stiffness: number; damping: number; mass: number}}
	| {{kind: 'linear'}};

/** A motion token: how long (frames at 60 fps), how late, and with which curve. */
export type Motion = {{duration: number; delay: number; ease: Ease}};

export const bezier = (x1: number, y1: number, x2: number, y2: number): Ease => ({{kind: 'bezier', x1, y1, x2, y2}});
export const springEase = (stiffness: number, damping: number, mass = 1): Ease => ({{kind: 'spring', stiffness, damping, mass}});
export const linear: Ease = {{kind: 'linear'}};

export const motion = (duration: number, ease: Ease, delay = 0): Motion => ({{duration, delay, ease}});

export const EASE = {{
{chr(10).join(lines)}
}} satisfies Record<string, Ease>;

export type EaseName = keyof typeof EASE;
"""
    OUT_EASE.write_text(ease_ts)

    rows = []
    for cid, c in sorted(tok["curves"].items()):
        rows.append(f"\t'{cid}': {{duration: {c['duration']}, ease: '{rename[c['ease']]}'}},")
    measured_ts = f"""// One motion per measured curve: the integer duration (60 fps) and the ease token that together
// reproduce it within 1 frame and RMSE 0.05 (scripts/verify.py). Generated by
// scripts/analysis/gen_tokens.py from analysis/tokens.json; keys are curve ids in analysis/<video>/curves.
import {{EASE, type EaseName, motion, type Motion}} from './easing';

type Measured = {{duration: number; ease: EaseName}};

export const MEASURED = {{
{chr(10).join(rows)}
}} as const satisfies Record<string, Measured>;

export type CurveId = keyof typeof MEASURED;

/** The measured motion of a curve, optionally delayed (frames at 60 fps). */
export const measured = (id: CurveId, delay = 0): Motion => {{
	const m: Measured = MEASURED[id];
	return motion(m.duration, EASE[m.ease], delay);
}};
"""
    OUT_MEASURED.write_text(measured_ts)
    print(f"{len(eases)} ease tokens -> {OUT_EASE.relative_to(ROOT)}; {len(rows)} curves -> {OUT_MEASURED.relative_to(ROOT)}")
    for k in order:
        print(f"  {rename[k]:24s} {eases[k]['uses']:4d}  {k}")


if __name__ == "__main__":
    main()
