"""The final report's tables (generated): analysis/REPORT.md.

  python report_tables.py

1. Per video: every segment (frames, length, class, the boundary out with its type and frames), from
   segments.json.
2. Per primitive: measured curves, measured and built durations, worst duration error and worst curve
   error (normalised RMSE), from analysis/verify/timing.json (written by scripts/verify.py).
3. Per curve technique: measured frames, built frames, RMSE.
"""
from collections import defaultdict

from common import ANALYSIS, load_json, load_registry


def main():
    out = ["# Report tables", "",
           "Generated by `scripts/analysis/report_tables.py` from every `segments.json` and `analysis/verify/timing.json`.", ""]
    out += ["## Segments", ""]
    for v in load_registry():
        d = load_json(v.dir / "segments.json")
        trans = {t["id"]: t for t in d.get("transitions", [])}
        segs = d["segments"]
        counts = defaultdict(int)
        for s in segs:
            counts[s["class"]] += 1
        out += [f"### {v.key} ({v.stem}): {len(segs)} segments, " + ", ".join(f"{k} {n}" for k, n in sorted(counts.items())), "",
                "| segment | frames | length | class | out |", "|---|---|---|---|---|"]
        for s in segs:
            b = s.get("boundary_out", "")
            t = trans.get(b)
            bo = f"{b} {t['type']} {t['frames']} f" if t else b
            out.append(f"| {s['id']} | f{s['start']}-f{s['end']} | {s['length_frames']} | {s['class']} | {bo} |")
        out.append("")
    rows = load_json(ANALYSIS / "verify" / "timing.json", [])
    by = defaultdict(list)
    for r in rows:
        by[r["primitive"]].append(r)
    out += ["## Primitives: measured vs built timing", "",
            f"{len(rows)} measured curves in {len(by)} primitives; limits: duration within 1 frame, normalised RMSE <= 0.05.", "",
            "| primitive | curves | measured frames | built frames | worst duration error (f) | worst RMSE | all ok |",
            "|---|---|---|---|---|---|---|"]
    for p, rs in sorted(by.items()):
        m = [r["measured_frames"] for r in rs]
        b = [r["built_frames"] for r in rs]
        err = max(abs(r["built_frames"] - r["measured_frames"]) for r in rs)
        out.append(f"| {p} | {len(rs)} | {min(m):.0f}-{max(m):.0f} | {min(b):.0f}-{max(b):.0f} | {err:.0f} | "
                   f"{max(r['rmse'] for r in rs):.4f} | {'yes' if all(r['ok'] for r in rs) else 'NO'} |")
    out += ["", "## Curve techniques", "", "| technique | primitive / variant | property | measured f | built f | RMSE |", "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: r["technique"]):
        out.append(f"| `{r['technique']}` | {r['primitive']} / {r['variant']} | {r['property']} | {r['measured_frames']:.0f} | "
                   f"{r['built_frames']:.0f} | {r['rmse']:.4f} |")
    (ANALYSIS / "REPORT.md").write_text("\n".join(out) + "\n")
    print(f"REPORT.md: {sum(1 for _ in load_registry())} videos, {len(by)} primitives, {len(rows)} curves")


if __name__ == "__main__":
    main()
