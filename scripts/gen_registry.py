#!/usr/bin/env python3
"""Regenerate the primitive registry from the files on disk.

Every primitive is two files in src/motion/primitives/<group>/:
  <Name>.spec.ts  pure data (tokens only, no React): `export const spec: PrimitiveSpec`
  <Name>.tsx      the reusable component `export const <Name>` and `export const Demo: React.FC<DemoProps>`
This writes src/motion/primitives/specs.ts (every spec, in catalogue order when
analysis/catalogue.json exists, else alphabetical) and src/motion/primitives/index.ts (name -> Demo).

  .venv/bin/python scripts/gen_registry.py
"""
from __future__ import annotations

import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PRIM = ROOT / "src" / "motion" / "primitives"


def main() -> None:
    found = []
    for spec in sorted(PRIM.glob("*/*.spec.ts")):
        name = spec.name[: -len(".spec.ts")]
        comp = spec.with_name(f"{name}.tsx")
        text = spec.read_text()
        if not re.search(r"export const spec\b", text):
            raise SystemExit(f"{spec.relative_to(ROOT)}: no `export const spec`")
        if not comp.exists():
            raise SystemExit(f"{spec.relative_to(ROOT)}: no component file {comp.name}")
        if not re.search(r"export const Demo\b", comp.read_text()):
            raise SystemExit(f"{comp.relative_to(ROOT)}: no `export const Demo`")
        found.append((spec.parent.name, name))
    order = {}
    cat = ROOT / "analysis" / "catalogue.json"
    if cat.exists():
        for i, p in enumerate(json.loads(cat.read_text()).get("primitives", [])):
            order[p["name"]] = i
    found.sort(key=lambda gn: (order.get(gn[1], 10_000), gn[1]))

    ident = lambda n: re.sub(r"\W", "_", n)  # noqa: E731
    spec_lines = [f"import {{spec as {ident(n)}}} from './{g}/{n}.spec';" for g, n in found]
    specs_ts = (
        "// Generated by scripts/gen_registry.py from src/motion/primitives/<group>/<Name>.spec.ts.\n"
        "// Pure data (tokens only, no React), so plain Node can read it (scripts/sample_curves.ts).\n"
        "import type {PrimitiveSpec} from './types';\n"
        + "\n".join(spec_lines)
        + "\n\nexport const SPECS: PrimitiveSpec[] = [\n"
        + "".join(f"\t{ident(n)},\n" for _, n in found)
        + "];\n"
    )
    comp_lines = [f"import {{Demo as {ident(n)}}} from './{g}/{n}';" for g, n in found]
    index_ts = (
        "// Generated by scripts/gen_registry.py: primitive name -> isolated demo component\n"
        "// (MotionShowcase, PrimitiveProbe).\n"
        "import type React from 'react';\n"
        "import type {DemoProps} from './types';\n"
        + "\n".join(comp_lines)
        + "\n\nexport const COMPONENTS: Record<string, React.FC<DemoProps>> = {\n"
        + "".join(f"\t{n}: {ident(n)},\n" for _, n in found)
        + "};\n"
    )
    (PRIM / "specs.ts").write_text(specs_ts)
    (PRIM / "index.ts").write_text(index_ts)
    print(f"{len(found)} primitives registered")


if __name__ == "__main__":
    main()
